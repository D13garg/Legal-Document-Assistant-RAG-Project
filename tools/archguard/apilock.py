"""api.lock: a snapshot of each module's public surface (AG080)."""

from __future__ import annotations

import ast
import copy
from pathlib import Path

from archguard import policy
from archguard.model import Violation

HEADER = "# generated by `python -m archguard api-lock --write`; review changes as API changes\n"


def _signature(node: ast.AST) -> str:
    clone = copy.deepcopy(node)
    assert isinstance(clone, ast.FunctionDef | ast.AsyncFunctionDef)  # noqa: S101
    clone.body = [ast.Expr(ast.Constant(value=...))]
    return " ".join(ast.unparse(clone).split())


def _describe(node: ast.AST) -> list[str]:
    if isinstance(node, ast.ClassDef):
        deco = "".join(f"@{ast.unparse(d)} " for d in node.decorator_list)
        bases = ", ".join(ast.unparse(b) for b in node.bases)
        lines = [f"{deco}class {node.name}({bases})"]
        for item in node.body:
            if isinstance(item, ast.AnnAssign | ast.Assign):
                lines.append("    " + ast.unparse(item))
            elif isinstance(item, ast.FunctionDef | ast.AsyncFunctionDef) and (
                not item.name.startswith("_") or item.name in ("__init__", "__call__")
            ):
                lines.append("    " + _signature(item))
        return lines
    if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
        return [_signature(node)]
    if isinstance(node, ast.Assign | ast.AnnAssign):
        return [ast.unparse(node)]
    return []


def _find(root: Path, dotted: str, name: str, depth: int = 0) -> list[str] | None:
    base = root / "src" / dotted.replace(".", "/")
    file = base.with_suffix(".py") if base.with_suffix(".py").exists() else base / "__init__.py"
    if not file.exists() or depth > 3:
        return None
    tree = ast.parse(file.read_text(encoding="utf-8"))
    for node in tree.body:
        defined = getattr(node, "name", None)
        if defined == name:
            return _describe(node)
        if isinstance(node, ast.Assign | ast.AnnAssign):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            if any(isinstance(t, ast.Name) and t.id == name for t in targets):
                return _describe(node)
        if (
            isinstance(node, ast.ImportFrom)
            and node.module
            and node.level == 0
            and any((a.asname or a.name) == name for a in node.names)
        ):
            orig = next(a.name for a in node.names if (a.asname or a.name) == name)
            return _find(root, node.module, orig, depth + 1)
    return None


def build_snapshot(root: Path, module: str) -> tuple[str, str | None]:
    """Return (snapshot_text, error). The error is set when __all__ is not a literal list."""
    init = root / policy.MODULES_ROOT / module / "api" / "__init__.py"
    tree = ast.parse(init.read_text(encoding="utf-8"))
    names: list[str] | None = None
    for node in tree.body:
        value = None
        if isinstance(node, ast.Assign):
            if any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
                value = node.value
        elif (
            isinstance(node, ast.AnnAssign)
            and isinstance(node.target, ast.Name)
            and node.target.id == "__all__"
        ):
            value = node.value
        if isinstance(value, ast.List | ast.Tuple) and all(
            isinstance(e, ast.Constant) and isinstance(e.value, str) for e in value.elts
        ):
            names = [str(e.value) for e in value.elts if isinstance(e, ast.Constant)]
    if names is None:
        return "", "api/__init__.py must define __all__ as a literal list of strings"
    pkg = f"lda.modules.{module}.api"
    lines = [HEADER.rstrip()]
    for name in sorted(names):
        described = _find(root, pkg, name)
        lines.append(f"## {name}")
        lines.extend(described if described else [f"<unresolved: {name}>"])
    return "\n".join(lines) + "\n", None


def check_api_locks(root: Path, modules: list[str]) -> list[Violation]:
    out: list[Violation] = []
    for m in modules:
        rel = f"{policy.MODULES_ROOT}/{m}/api.lock"
        if not (root / policy.MODULES_ROOT / m / "api" / "__init__.py").exists():
            continue
        text, err = build_snapshot(root, m)
        if err:
            out.append(Violation("AG080", f"{policy.MODULES_ROOT}/{m}/api/__init__.py", 0, err))
            continue
        lock = root / rel
        if not lock.exists() or lock.read_text(encoding="utf-8") != text:
            out.append(
                Violation(
                    "AG080",
                    rel,
                    0,
                    "public API changed; run `python -m archguard api-lock --write` and add/update an ADR",
                )
            )
        if "<unresolved:" in text:
            out.append(
                Violation(
                    "AG080", rel, 0, "api exports a name that cannot be resolved to a definition"
                )
            )
    return out


def write_api_locks(root: Path, modules: list[str]) -> None:
    for m in modules:
        text, err = build_snapshot(root, m)
        if err:
            raise SystemExit(f"{m}: {err}")
        (root / policy.MODULES_ROOT / m / "api.lock").write_text(text, encoding="utf-8")
