"""Generates .importlinter from module manifests and the approved DAG (ADR-025).

import-linter enforces internal layering and import *chains*; third-party purity is enforced by
archguard (AG030), whose allow-list is stricter than a deny-list and needs no installed packages.
"""

from __future__ import annotations

from collections.abc import Sequence

from archguard.manifest import Manifest, topological_order

HEADER = "# GENERATED by `python -m archguard gen-importlinter`. Do not edit.\n"


def _contract(cid: str, name: str, type_: str, **fields: list[str]) -> str:
    lines = [f"[importlinter:contract:{cid}]", f"name = {name}", f"type = {type_}"]
    for key, values in fields.items():
        lines.append(f"{key} =")
        lines.extend(f"    {v}" for v in values)
    return "\n".join(lines) + "\n"


def generate(
    manifests: dict[str, Manifest],
    dag: dict[str, tuple[str, ...]],
    platform_parts: Sequence[str] = (),
) -> str:
    """`platform_parts` are the `lda.platform.<part>` packages other than `testing` (see runner)."""
    parts = [HEADER, "[importlinter]\nroot_packages =\n    lda\n"]
    parts.append(
        _contract(
            "kernel-pure",
            "shared.kernel imports nothing else in the repo",
            "forbidden",
            source_modules=["lda.shared.kernel"],
            forbidden_modules=["lda.shared.ports", "lda.platform", "lda.bootstrap", "lda.modules"],
        )
    )
    parts.append(
        _contract(
            "ports-minimal",
            "shared.ports depends only on kernel",
            "forbidden",
            source_modules=["lda.shared.ports"],
            forbidden_modules=["lda.platform", "lda.bootstrap", "lda.modules"],
        )
    )
    parts.append(
        _contract(
            "platform-isolated",
            "platform never imports modules or bootstrap",
            "forbidden",
            source_modules=["lda.platform"],
            forbidden_modules=["lda.modules", "lda.bootstrap"],
        )
    )
    parts.append(
        _contract(
            "modules-not-composition",
            "modules never import bootstrap",
            "forbidden",
            source_modules=["lda.modules"],
            forbidden_modules=["lda.bootstrap"],
        )
    )
    for name in sorted(manifests):
        m = manifests[name]
        base = f"lda.modules.{name}"
        top = [
            f"{base}.{x}"
            for x in ("api", "presentation", "infrastructure")
            if x == "api" or x in m.layers
        ]
        rows = [" | ".join(top)]
        for x in ("application", "domain"):
            if x in m.layers:
                rows.append(f"{base}.{x}")
        if len(rows) > 1:
            parts.append(
                _contract(
                    f"{name}-layers",
                    f"{name}: layered (presentation|infrastructure|api > application > domain)",
                    "layers",
                    layers=rows,
                )
            )
        if "domain" in m.layers:
            parts.append(
                _contract(
                    f"{name}-domain-pure",
                    f"{name}: domain has no ports/platform/bootstrap",
                    "forbidden",
                    source_modules=[f"{base}.domain"],
                    forbidden_modules=["lda.shared.ports", "lda.platform", "lda.bootstrap"],
                )
            )
        inner = [
            f"{base}.{x}"
            for x in ("application", "api", "presentation")
            if x == "api" or x in m.layers
        ]
        parts.append(
            _contract(
                f"{name}-no-platform",
                f"{name}: only infrastructure may use platform",
                "forbidden",
                source_modules=inner,
                forbidden_modules=["lda.platform"],
            )
        )
        if platform_parts:
            # AG020: testing/ may import lda.platform.testing (in-memory doubles) and nothing else
            # of the platform. Listing every other part keeps that exact, with no ignore_imports.
            parts.append(
                _contract(
                    f"{name}-testing-platform",
                    f"{name}: testing may use only platform.testing",
                    "forbidden",
                    source_modules=[f"{base}.testing"],
                    forbidden_modules=[f"lda.platform.{p}" for p in sorted(platform_parts)],
                )
            )
    if len(manifests) > 1:
        order = topological_order(dag, set(manifests))
        parts.append(
            _contract(
                "module-dag-order",
                "modules only depend downward in the approved DAG order",
                "layers",
                layers=[f"lda.modules.{n}" for n in order],
            )
        )
    return "\n".join(parts)
